def reset_playlist():
    global _playlist_index, _playlist_last
    _playlist_index = 0
    _playlist_last = 0.0


def current_rotation(config):
    """Scripts and seconds for the active group, or the old playlist."""
    active = config.get("active_group")
    for group in config.get("groups") or []:
        if isinstance(group, dict) and group.get("name") == active:
            return group.get("scripts") or [], group.get("seconds") or 60
    return config.get("playlist") or [], config.get("playlist_seconds") or 60


def playlist_loop():
    """Rotate through the active group or playlist."""
    global _playlist_index, _playlist_last
    while True:
        time.sleep(1)
        config = read_config()
        names, raw_seconds = current_rotation(config)
        if not names:
            continue
        try:
            seconds = max(5, int(raw_seconds))
        except (TypeError, ValueError):
            seconds = 60
        now = time.time()
        if _playlist_last and now - _playlist_last < seconds:
            continue
        name = names[_playlist_index % len(names)]
        refresh_registry()
        if name in SCRIPT_REGISTRY:
            try:
                start_child(name)
                print("server: playlist -> %s" % name)
            except Exception as exc:
                print("server: playlist start failed:", exc)
        _playlist_index += 1
        _playlist_last = now


def detect_device():
    """Once per 30 s: which display is physically attached.

    - `microdot-phat`: I2C chips 0x61/0x62/0x63 answer (definitive)
    - `unicorn-hat 16x8`: device-tree HAT EEPROM product string (definitive)
    - `unicorn phat 8x4 (inferred)`: neither of the above; ws281x strips give
      no electrical ack, so presence is inferred, not sensed
    - `none-probed`: neither microdot chips nor any other known sign
    """
    global _attached, _last_detect
    with _detect_lock:
        if _attached and time.time() - _last_detect < 30:
            return _attached
        kind = "none-probed"
        if _microdot_present():
            kind = "microdot-phat"
        if kind == "none-probed":
            try:
                product = open("/proc/device-tree/hat/product", "rb").read()
                product = product.rstrip(b" ").decode("ascii", "ignore").strip()
                if product.startswith("Unicorn HAT"):
                    kind = "unicorn-hat 16x8"
            except OSError:
                pass
        if kind == "none-probed":
            kind = "unicorn phat (inferred)"
        _attached = kind
        _last_detect = time.time()
        print("server: attached display detected:", kind)
        return kind


