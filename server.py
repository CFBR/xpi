def write_script_file(path, text):
    """Write a script beside its destination, then replace atomically."""
    directory = os.path.dirname(path)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".script-", suffix=".py")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.chmod(tmp, 0o644)
        try:
            os.chown(tmp, 1000, 1000)
        except OSError:
            pass
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def read_frame():
    """The last frame published by the display libraries, or available=false."""
    try:
        with open(FRAME_FILE) as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {"available": False}
    if not isinstance(data, dict):
        return {"available": False}
    try:
        age = max(0.0, time.time() - float(data.get("ts")))
    except (TypeError, ValueError):
        age = 0.0
    data.pop("ts", None)
    data["available"] = True
    data["age"] = round(age, 2)
    return data


