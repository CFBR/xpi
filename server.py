_tag_cache = {}


def _board_from_source(path):
    """Board tag from imports, cached by path and file stat."""
    try:
        info = os.stat(path)
    except OSError:
        return ""
    key = (info.st_mtime_ns, info.st_size)
    cached = _tag_cache.get(path)
    if cached is not None and cached[0] == key:
        return cached[1]
    try:
        with open(path) as fh:
            src = fh.read()
    except OSError:
        return ""
    found = set()
    try:
        import ast
        tree = ast.parse(src)
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    found.add(alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom) and node.module:
                found.add(node.module.split(".")[0])
    except SyntaxError:
        found = set(re.findall(r"\b(?:import|from)\s+([A-Za-z_][\w.]*)", src))
        has_micro = "microdotphat" in src
        has_unicorn = "unicornhat" in src
    else:
        has_micro = "microdotphat" in found
        has_unicorn = "unicornhat" in found
    if has_micro and has_unicorn:
        tag = "both"
    elif has_micro:
        tag = "microdot-phat"
    elif has_unicorn:
        tag = "unicorn-hat"
    else:
        tag = "generic"
    _tag_cache[path] = (key, tag)
    return tag


def _board_from_dir(directory):
    for tag in (("/scripts/unicorn-hat/phat", "unicorn phat 8x4"),
                ("/scripts/unicorn-hat/hat", "unicorn-hat 16x8"),
                ("/scripts/microdot-phat", "microdot-phat"),
                ("/scripts/unicorn-hat", "unicorn-hat")):
        if tag[0] in directory:
            return tag[1]
    return "generic"


def scan_scripts():
    """Return (registry, board tags) keyed by filename stem.

    The first scan-dir occurrence wins. Builds new dicts so a refresh can
    swap them in without a reader ever seeing a half-filled registry.
    """
    registry = {}
    tags = {}
    for directory in SCAN_DIRS:
        if not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            if not name.endswith(".py") or name.startswith("_"):
                continue
            stem = name[:-3]
            if stem in registry:
                print("server: duplicate stem %r, keeping %s"
                      % (stem, registry[stem]))
                continue
            registry[stem] = os.path.join(directory, name)
            tag = _board_from_dir(directory)
            if tag == "generic":
                tag = _board_from_source(registry[stem])
            tags[stem] = tag
    return registry, tags


