_log_lock = threading.Lock()
_log_chunks = collections.deque(maxlen=512)
_sup_lock = threading.RLock()  # serializes start/stop (reentrant: start calls stop)


def child_env():
    env = os.environ.copy()
    inherited = env.get("PYTHONPATH", "")
    extra = [SUPPORT_DIR, SCRIPTS_DIR] + [p for p in REPO_LIBPATHS if os.path.isdir(p)]
    joined = ":".join(extra)
    env["PYTHONPATH"] = inherited + ":" + joined if inherited else joined
    return env


def _pump(stdout):
    try:
        while True:
            data = os.read(stdout.fileno(), 1024)
            if not data:
                break
            with _log_lock:
                for i in range(0, len(data), 128):
                    _log_chunks.append(data[i:i + 128])
    except OSError:
        pass


def start_child(stem, args=()):
    global _child, _child_args, _child_started
    path = SCRIPT_REGISTRY[stem]
    with _sup_lock:
        # stop old child and blank the board so its last frame
        # doesn't bleed under the new script; kept in the log ring
        with _log_lock:
            _log_chunks.clear()
        clear_board()
        _child = subprocess.Popen(
            [sys.executable, "-u", path, *args],
            cwd=os.path.dirname(path), env=child_env(),
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        _child_args = list(args)
        _child_started = time.time()
    threading.Thread(target=_pump, args=(_child.stdout,), daemon=True).start()
    print("server: started %s (pid %d)" % (stem, _child.pid))


def stop_child():
    """SIGINT -> 2 s -> SIGTERM -> 2 s -> SIGKILL."""
    global _child, _child_args, _child_started
    if _child is None:
        return
    with _sup_lock:
        child = _child
        _child = None
        _child_args = []
        _child_started = None
        for sig_int in (signal.SIGINT, signal.SIGTERM, signal.SIGKILL):
            if child.poll() is not None:
                break
            child.send_signal(sig_int)
            deadline = time.time() + 2
            while time.time() < deadline and child.poll() is None:
                time.sleep(0.05)
        child.wait()
        with _log_lock:
            _log_chunks.append(b"[%d stopped]\n" % child.pid)
        print("server: stopped pid %d" % child.pid)


def running_child():
    if _child is not None and _child.poll() is not None:
        return None          # died on its own; not "running"
    return _child


def log_text(tail=1200):
    with _log_lock:
        return b"".join(_log_chunks).decode("utf-8", "replace")[-tail:]


def clear_target():
    """Which board clear.py should touch, from the cached detection."""
    kind = detect_device()
    if kind == "microdot-phat":
        return "microdot"
    if kind.startswith("unicorn"):
        return "unicorn"
    return None


_clear_proc = None
_clear_lock = threading.Lock()


def _clear_reply(proc, timeout=10):
    deadline = time.time() + timeout
    while time.time() < deadline:
        wait = max(0.0, deadline - time.time())
        ready, _, _ = select.select([proc.stdout], [], [], wait)
        if not ready:
            return None
        line = proc.stdout.readline()
        if not line:
            return None
        line = line.strip()
        if line.startswith("OK") or line.startswith("ERR"):
            return line
    return None


def clear_via_daemon(target):
    """Clear through a warm helper process, or return False to use clear.py."""
    global _clear_proc
    with _clear_lock:
        if _clear_proc is None or _clear_proc.poll() is not None:
            _clear_proc = subprocess.Popen(
                [sys.executable, "-u", os.path.join(SUPPORT_DIR, "clear_daemon.py")],
                cwd=SUPPORT_DIR, env=child_env(),
                stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT, text=True, bufsize=1)
        try:
            _clear_proc.stdin.write((target or "all") + "\n")
            _clear_proc.stdin.flush()
            reply = _clear_reply(_clear_proc)
        except (OSError, ValueError) as exc:
            reply = "ERR %s" % exc
        if reply and reply.startswith("OK"):
            return True
        print("server: clear daemon failed:", reply or "timeout")
        try:
            _clear_proc.kill()
        except OSError:
            pass
        _clear_proc = None
        return False


def stop_clear_daemon():
    global _clear_proc
    with _clear_lock:
        if _clear_proc is not None:
            try:
                _clear_proc.terminate()
            except OSError:
                pass
            _clear_proc = None


def clear_board():
    result = None
    target = clear_target()
    started = time.time()
    with _sup_lock:
        stop_child()
        if clear_via_daemon(target):
            out = b"clear.py: direct clear\n"
            result = 0
        else:
            cmd = [sys.executable, os.path.join(SCRIPTS_DIR, "clear.py")]
            if target:
                cmd.append(target)
            try:
                result = subprocess.run(
                    cmd,
                    cwd=SCRIPTS_DIR, env=child_env(), timeout=5,
                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
                out = result.stdout
            except subprocess.TimeoutExpired as exc:
                # a board probe hanging (e.g. no display of the other kind
                # attached) must never block switching; wipe what responded
                out = exc.stdout or b""
                out += b"\n[clear timed out; wiped what responded]\n"
    out += ("\n[clear %.2fs]\n" % (time.time() - started)).encode()
    with _log_lock:
        _log_chunks.clear()
        for i in range(0, len(out), 128):
            _log_chunks.append(out[i:i + 128])
    return result.returncode if result else 0


